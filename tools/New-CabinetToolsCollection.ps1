<#
.SYNOPSIS
  Puts the ArcadeMaster maintenance commands into the frontend: a "Tools" collection whose items are
  .bat launchers for Invoke-CabinetTool.ps1 (wheel setup, detect controllers, repair IDs, rebuild menus,
  FFB / second screen / perf log toggles, shuffle backgrounds, cabinet settings, themes, reset theme). Neon logo per item, RetroFE restarts after
  each tool (launcher reboot = yes) so settings apply. Adds Tools to Main\menu.txt.
  Marked ARCADEMASTER-TOOLS.txt (New-RetroFECollections leaves it alone; Build-Manifest skips it).
#>
param(
  [string]$RetroFE = 'D:\ArcadeMaster\frontend\DRIVE-coinops',
  [string]$ToolsDir = $PSScriptRoot,
  [string]$ManifestDir = 'D:\ArcadeMaster\manifest',
  [switch]$Remove
)
$ErrorActionPreference = 'Stop'
$col = Join-Path $RetroFE 'collections\Tools'
$menuTxt = Join-Path $RetroFE 'collections\Main\menu.txt'
if ($Remove) {
  if (Test-Path (Join-Path $col 'ARCADEMASTER-TOOLS.txt')) { Remove-Item $col -Recurse -Force }
  Remove-Item (Join-Path $RetroFE 'launchers.windows\AM_TOOLS.conf') -ErrorAction SilentlyContinue
  if (Test-Path $menuTxt) { Set-Content $menuTxt (@(Get-Content $menuTxt) | Where-Object { $_ -ne 'Tools' }) -Encoding ascii }
  Write-Host 'Tools collection removed'; return
}

$items = [ordered]@{
  '0 Cabinet Settings'       = @('SystemSettings', 'ffb000')
  '00 System Health'         = @('SystemHealth', '3ddc84')
  '0a Menu Buttons'          = @('MenuButtons', '2ec8ff')
  '1 Wheel Setup'            = @('WheelSetup', 'ff2fa0')
  '2 Detect Controllers'     = @('DetectControllers', '2ec8ff')
  '3 Repair Controller IDs'  = @('RepairIds', '2ec8ff')
  '4 Rebuild Game Menus'     = @('RebuildMenus', 'ffb000')
  '5 Force Feedback On-Off'  = @('ToggleFfb', 'ff2fa0')
  '5a Bass Shakers On-Off'   = @('ToggleTactile', 'ff6a00')
  '6 Second Screen On-Off'   = @('ToggleSecondScreen', '9be7ff')
  '7 Shuffle Backgrounds'    = @('ShuffleBackgrounds', '7b5cff')
  '7a Menu Music'            = @('MenuMusic', 'ff2fa0')
  '8 Performance Log On-Off' = @('TogglePerfLog', '9aa3b2')
  '9 Cabinet Type'           = @('CabinetType', '2ec8ff')
  '9a Themes'                = @('Themes', '7b5cff')
  '9b Reset Theme'           = @('ResetTheme', '7b5cff')
  '9c Graphics Driver'       = @('GpuDriver', '3ddc84')
  '9y Restart PC'            = @('RestartPC', 'ffb000')
  '9z Shut Down PC'          = @('ShutdownPC', 'ff4d4d')
  '9d Emulator Updates'      = @('EmulatorUpdates', '3ddc84')
}

# a cabinet with no wheel (pedestal, stand-up) does not need the wheel and force-feedback items
$cabFile = Join-Path $ManifestDir 'cabinet.json'
if (Test-Path $cabFile) {
  $cap = (Get-Content $cabFile -Raw | ConvertFrom-Json).capabilities
  if ($cap -and -not $cap.wheel) { $items.Remove('1 Wheel Setup'); if (-not $cap.ffb) { $items.Remove('5 Force Feedback On-Off') }; $items.Remove('5a Bass Shakers On-Off') }
  # a control-panel cabinet gets the panel's counterpart of Wheel Setup: see what every button and stick sends
  if ($cap -and $cap.controlPanel) { $items.Insert(2, '1 Panel Test', @('PanelTest', 'ff2fa0')) }
  # a flight stick / HOTAS plugged in: its own setup wizard (the boot rebuilds this list when one appears or goes)
  if ($cap -and $cap.flightStick) { $items.Insert(2, '1a Flight Stick Setup', @('FlightSetup', '2ec8ff')) }
}

if (Test-Path $col) { Remove-Item $col -Recurse -Force }
New-Item -ItemType Directory -Force (Join-Path $col 'roms') | Out-Null
Set-Content (Join-Path $col 'ARCADEMASTER-TOOLS.txt') 'generated by tools/New-CabinetToolsCollection.ps1 - re-run it to regenerate, -Remove to delete' -Encoding ascii
Set-Content (Join-Path $col 'settings.conf') "# ArcadeMaster cabinet tools`r`nlist.extensions = bat`r`nlist.includeMissingItems = false`r`nlist.menuSort = yes`r`nlauncher = AM_TOOLS`r`nmetadata.type = %ITEM_COLLECTION_NAME%`r`n" -Encoding ascii
# wscript runs the .bat with NO console window (a console from a GUI process opens a desktop-sized Windows
# Terminal); the .bat starts Show-ToolScreen, a full-screen window sized to the cabinet display
Set-Content (Join-Path $col 'RunHidden.vbs') "' ArcadeMaster: run a Tools .bat without a console window and wait for it`r`nCreateObject(`"WScript.Shell`").Run `"cmd /c `"`"`" & WScript.Arguments(0) & `"`"`"`", 0, True`r`n" -Encoding ascii
Set-Content (Join-Path $RetroFE 'launchers.windows\AM_TOOLS.conf') "executable = C:\Windows\System32\wscript.exe`r`narguments = `"$col\RunHidden.vbs`" `"%ITEM_FILEPATH%`"`r`nreboot = yes" -Encoding ascii

foreach ($name in $items.Keys) {
  $id = $items[$name][0]
  $label = ($name -replace '^\d+[a-z]?\s+', '').ToUpper()
  # the .bat shows the tool on a full-screen visual page (scaled to the display) and returns when it is closed
  Set-Content (Join-Path $col "roms\$name.bat") ("@echo off`r`npowershell -NoProfile -ExecutionPolicy Bypass -File `"$ToolsDir\Show-ToolScreen.ps1`" -Tool $id -Title `"$label`" -RetroFE `"$RetroFE`" -ManifestDir `"$ManifestDir`"`r`n") -Encoding ascii
}
# logos (with live ON/OFF switches), preview cards with the cabinet's current state, backdrops
& (Join-Path $ToolsDir 'New-ToolsArt.ps1') -RetroFE $RetroFE -ManifestDir $ManifestDir
# the CoinOPS "Settings" stop at the end of the Left/Right filters (playlist zSettings = _zzzShutdown:*) ran CoinOPS's
# view-mode scripts (zzARCADE, zzWHEEL, zNightDay ...) that don't fit the ArcadeMaster layout (James 2026-11-26: "should
# be a theme settings and then you select choices with preview - it's currently all scripts"). It shows these Tools
# instead - Cabinet Settings, Themes with previews, ... - with their art; Shutdown stays. CoinOPS's scripts are kept in
# roms.am-coinops.
$zs = Join-Path $RetroFE 'collections\zzzShutdown'
if (Test-Path (Join-Path $zs 'roms')) {
  $keep = Join-Path $zs 'roms.am-coinops'; New-Item -ItemType Directory -Force $keep | Out-Null
  Get-ChildItem (Join-Path $zs 'roms') -File | Where-Object { $_.Name -match '^z.*\.bat$' } | ForEach-Object { Move-Item $_.FullName (Join-Path $keep $_.Name) -Force }
  Get-ChildItem (Join-Path $zs 'roms') -File -Filter '*.bat' | Where-Object { $_.Name -ne 'Shutdown.bat' -and -not $items.Contains($_.BaseName) } | Remove-Item -Force   # tools no longer offered
  $ld = Join-Path $zs 'Launchers'; New-Item -ItemType Directory -Force $ld | Out-Null
  foreach ($name in $items.Keys) {
    Copy-Item (Join-Path $col "roms\$name.bat") (Join-Path $zs "roms\$name.bat") -Force
    Set-Content (Join-Path $ld "$name.conf") 'AM_TOOLS' -Encoding ascii
  }
  foreach ($kind in Get-ChildItem (Join-Path $col 'medium_artwork') -Directory -ErrorAction SilentlyContinue) {
    $dst = Join-Path $zs "medium_artwork\$($kind.Name)"; New-Item -ItemType Directory -Force $dst | Out-Null
    Get-ChildItem $kind.FullName -File | ForEach-Object { Copy-Item $_.FullName (Join-Path $dst $_.Name) -Force }
  }
  $sub = Join-Path $RetroFE 'collections\Arcade\zzzShutdown.sub'
  if (Test-Path $sub) { Set-Content $sub (@($items.Keys) + 'Shutdown') -Encoding ascii }
  Write-Host ("Settings stop (zzzShutdown): {0} tools + Shutdown" -f $items.Count)
}
# main menu entry (after the game categories / Settings)
if (Test-Path $menuTxt) { $menu = @(Get-Content $menuTxt | Where-Object { $_.Trim() }); if ($menu -notcontains 'Tools') { Set-Content $menuTxt ($menu + 'Tools') -Encoding ascii } }
Write-Host ("Tools collection: {0} items -> {1}" -f $items.Count, $col)
